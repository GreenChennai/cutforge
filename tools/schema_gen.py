def build_generated() -> str:
    schemas = {}
    for name in SCHEMA_FILES:
        p = SCHEMA_DIR / f"{name}.schema.json"
        if not p.exists():
            raise FileNotFoundError(f"schema 缺失: {p}")
        schemas[name] = json.loads(p.read_text("utf-8"))
    payload = json.dumps(schemas, ensure_ascii=False, sort_keys=True)
    if "'''" in payload:
        # 原始三引号字符串无法安全承载;契约描述里出现 ''' 属于契约缺陷,拒绝生成
        raise ValueError("schema 描述包含 ''' 字符,请改写描述后再生成")
    return TEMPLATE.format(SCHEMAS=payload, SQS="'''")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="生成 tools/_generated/cf_validate.py")
    ap.add_argument("--check", action="store_true", help="只校验生成物未过期")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)

    def emit(ok: bool, code: str, msg: str, data: dict) -> int:
        env = {"ok": ok, "code": code, "message": msg, "data": data}
        print(json.dumps(env, ensure_ascii=False, indent=2) if args.json else msg)
        return {"OK": 0, "GEN_STALE": 2, "NO_ENV": 3, "INTERNAL": 4}.get(code, 4)

    try:
        text = build_generated()
    except FileNotFoundError as exc:
        return emit(False, "NO_ENV", str(exc), {})
    except Exception as exc:  # noqa: BLE001
        return emit(False, "INTERNAL", f"生成失败: {exc!r}", {})

    if args.check:
        if not OUT_PATH.exists():
            return emit(False, "GEN_STALE", f"生成物不存在: {OUT_PATH}", {})
        if OUT_PATH.read_text("utf-8") != text:
            return emit(False, "GEN_STALE", "生成物过期(schema 已变,重新生成)", {}, )
        return emit(True, "OK", "生成物与 schema 一致", {"path": str(OUT_PATH)})
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(text, encoding="utf-8", newline="\n")
    return emit(True, "OK", f"已写入 {OUT_PATH}", {"path": str(OUT_PATH)})


if __name__ == "__main__":
    sys.exit(main())
