def _resolve(schema: dict, root: dict) -> dict:
    while "$ref" in schema:
        ref = schema["$ref"]
        if not ref.startswith("#/"):
            raise ValueError(f"不支持的外部引用: {{ref}}")
        node = root
        for part in ref[2:].split("/"):
            node = node[part.replace("~1", "/").replace("~0", "~")]
        schema = node
    return schema


def _check_type(types: list[str], data) -> bool:
    if data is None:
        return "null" in types
    types = [t for t in types if t != "null"] or types
    if types == ["integer"]:
        return isinstance(data, int) and not isinstance(data, bool)
    if "integer" in types:
        return (isinstance(data, int) and not isinstance(data, bool)) or (
            "number" in types and isinstance(data, float))
    if "number" in types:
        return isinstance(data, (int, float)) and not isinstance(data, bool)
    if "string" in types:
        return isinstance(data, str)
    if "boolean" in types:
        return isinstance(data, bool)
    if "object" in types:
        return isinstance(data, dict)
    if "array" in types:
        return isinstance(data, list)
    if "null" in types:
        return data is None
    return False


def validate(schema_name: str, data, path: str = "$") -> list[str]:
    """返回错误列表;空列表 = 通过。支持 draft-07 子集 + 两个 x- 断言。"""
    root = SCHEMAS[schema_name]
    return _validate(root, root, data, path)


def _validate(schema: dict, root: dict, data, path: str) -> list[str]:
    errors: list[str] = []
    schema = _resolve(schema, root)

    if "const" in schema and data != schema["const"]:
        errors.append(f"{{path}}: const 期望 {{schema['const']!r}} 实际 {{data!r}}")
        return errors
    if "enum" in schema and data not in schema["enum"]:
        errors.append(f"{{path}}: enum {{schema['enum']!r}} 不含 {{data!r}}")
        return errors

    t = schema.get("type")
    if t is not None:
        types = t if isinstance(t, list) else [t]
        if not _check_type(types, data):
            errors.append(f"{{path}}: type 期望 {{types}} 实际 {{type(data).__name__}}")
            return errors

    if isinstance(data, bool):
        return errors  # bool 是 int 子类,后续数值断言不适用

    if isinstance(data, (int, float)):
        if "minimum" in schema and data < schema["minimum"]:
            errors.append(f"{{path}}: minimum {{schema['minimum']}} 实际 {{data}}")
        if "maximum" in schema and data > schema["maximum"]:
            errors.append(f"{{path}}: maximum {{schema['maximum']}} 实际 {{data}}")
        if "exclusiveMinimum" in schema and data <= schema["exclusiveMinimum"]:
            errors.append(f"{{path}}: exclusiveMinimum {{schema['exclusiveMinimum']}} 实际 {{data}}")

    if isinstance(data, str):
        if "minLength" in schema and len(data) < schema["minLength"]:
            errors.append(f"{{path}}: minLength {{schema['minLength']}} 实际长度 {{len(data)}}")
        if "maxLength" in schema and len(data) > schema["maxLength"]:
            errors.append(f"{{path}}: maxLength {{schema['maxLength']}} 实际长度 {{len(data)}}")
        if "pattern" in schema and re.search(schema["pattern"], data) is None:
            errors.append(f"{{path}}: pattern {{schema['pattern']!r}} 不匹配 {{data!r}}")

    if isinstance(data, list):
        if "minItems" in schema and len(data) < schema["minItems"]:
            errors.append(f"{{path}}: minItems {{schema['minItems']}} 实际 {{len(data)}}")
        if "maxItems" in schema and len(data) > schema["maxItems"]:
            errors.append(f"{{path}}: maxItems {{schema['maxItems']}} 实际 {{len(data)}}")
        item = schema.get("items")
        if isinstance(item, dict):
            for i, el in enumerate(data):
                errors.extend(_validate(item, root, el, f"{{path}}[{{i}}]"))

    if isinstance(data, dict):
        for k in schema.get("required", []):
            if k not in data:
                errors.append(f"{{path}}: 缺必填键 '{{k}}'")
        props = schema.get("properties", {{}})
        for k, v in data.items():
            if k in props:
                errors.extend(_validate(props[k], root, v, f"{{path}}.{{k}}"))
            elif schema.get("additionalProperties") is False:
                errors.append(f"{{path}}: additionalProperties=false 拒绝多余键 '{{k}}'")

    # ---- 自定义跨字段断言(计划书 3.5:SKILL Hard Rule 3 进契约) ----
    if schema.get("x-removeRequiresGuardOk") and isinstance(data, dict) and data.get("action") == "remove":
        guard = data.get("guard")
        if not isinstance(guard, dict) or not guard:
            errors.append(f"{{path}}: action=remove 但 guard 为空(guard_passed 视为未过)")
        else:
            ok = guard.get("okByReason") if "okByReason" in guard else guard.get("ok")
            if ok is not True:
                errors.append(f"{{path}}: action=remove 但 guard 判定 ok={{ok!r}}")
            if guard.get("wordClipped") is True:
                errors.append(f"{{path}}: action=remove 但 wordClipped=true(任何 reason 下硬失败)")
    if schema.get("x-keepCoversTimeline") and isinstance(data, dict):
        keep = data.get("keep")
        total = data.get("srcTotalMs")
        if isinstance(keep, list) and isinstance(total, int):
            cur = 0
            ok_order = True
            for seg in keep:
                if (not isinstance(seg, list) or len(seg) != 2
                        or not all(isinstance(x, int) for x in seg) or seg[0] < cur or seg[1] < seg[0]):
                    ok_order = False
                    break
                cur = seg[1]
            if not ok_order:
                errors.append(f"{{path}}: keep 区间无序/重叠/非法")
            elif cur != total:
                errors.append(f"{{path}}: keep 覆盖到 {{cur}} ≠ srcTotalMs {{total}}")
    return errors


TRACK_LETTER = {{"video": "V", "audio": "A", "text": "T"}}


def migrate_project_v1_to_v2(doc: dict) -> dict:
    """v1→v2 迁移(计划书 3.3):幂等——对同一输入迁移两次,结果相等。"""
    if not isinstance(doc, dict):
        raise ValueError("project 文档必须是 object")
    out = copy.deepcopy(doc)
    out.setdefault("schemaVersion", "2.0.0")
    out.setdefault("backends", ["ffmpeg"])
    out.setdefault("notes", "notes.json")
    for ti, track in enumerate(out.get("tracks", [])):
        tid = track.get("id") or (
            f"{{TRACK_LETTER.get(track.get('kind', ''), 'X')}}{{ti + 1}}")
        track["id"] = tid
        for ci, clip in enumerate(track.get("clips", [])):
            clip["id"] = clip.get("id") or f"{{tid}}-{{ci + 1:03d}}"
    return out


